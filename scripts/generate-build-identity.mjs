import { createHash } from "node:crypto";
import { readdir, readFile, mkdir, writeFile } from "node:fs/promises";
import { dirname, relative, resolve, sep } from "node:path";
import process from "node:process";

const root = resolve(import.meta.dirname, "..");
const generatedModule = "src/generated/buildIdentity.ts";
const publicManifest = "public/portviewer-build-identity.json";
const distManifest = "portviewer-build-identity.json";

async function collectFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map(async (entry) => {
      const path = resolve(directory, entry.name);
      return entry.isDirectory() ? collectFiles(path) : [path];
    }),
  );
  return nested.flat();
}

function normalizedRelativePath(path, base) {
  return relative(base, path).split(sep).join("/");
}

function sortFiles(files, base) {
  return files.sort((left, right) => {
    const leftPath = normalizedRelativePath(left, base);
    const rightPath = normalizedRelativePath(right, base);
    return leftPath < rightPath ? -1 : leftPath > rightPath ? 1 : 0;
  });
}

async function calculateFilesHash(files, base) {
  const hash = createHash("sha256");
  for (const path of sortFiles(files, base)) {
    hash.update(normalizedRelativePath(path, base));
    hash.update(Buffer.from([0]));
    hash.update(await readFile(path));
    hash.update(Buffer.from([255]));
  }
  return hash.digest("hex");
}

async function generateSourceIdentity() {
  const productPackage = JSON.parse(
    await readFile(resolve(root, "package.json"), "utf8"),
  );
  const sourceFiles = [
    "index.html",
    "package.json",
    "package-lock.json",
    "vite.config.ts",
    "tsconfig.json",
    "tsconfig.app.json",
    "tsconfig.node.json",
    "scripts/generate-build-identity.mjs",
  ].map((path) => resolve(root, path));
  sourceFiles.push(
    ...(await collectFiles(resolve(root, "src"))),
    ...(await collectFiles(resolve(root, "public"))),
  );
  const sourceHash = await calculateFilesHash(
    sourceFiles.filter((path) => {
      const relativePath = normalizedRelativePath(path, root);
      return (
        relativePath !== generatedModule && relativePath !== publicManifest
      );
    }),
    root,
  );
  const identity = {
    schemaVersion: 1,
    productId: "com.portviewer.desktop",
    productVersion: productPackage.version,
    frontendContractVersion: 1,
    sourceHash,
  };
  const json = `${JSON.stringify(identity, null, 2)}\n`;
  const moduleSource = `// Generated by scripts/generate-build-identity.mjs. Do not edit.\nexport const FRONTEND_BUILD_IDENTITY = ${JSON.stringify(identity, null, 2)} as const;\n`;

  for (const [path, contents] of [
    [generatedModule, moduleSource],
    [publicManifest, json],
  ]) {
    const absolutePath = resolve(root, path);
    await mkdir(dirname(absolutePath), { recursive: true });
    await writeFile(absolutePath, contents, "utf8");
  }
  process.stdout.write(`PortViewer frontend source identity: ${sourceHash}\n`);
}

async function finalizeDistIdentity() {
  const distRoot = resolve(root, "dist");
  const manifestPath = resolve(distRoot, distManifest);
  const identity = JSON.parse(await readFile(manifestPath, "utf8"));
  const distFiles = (await collectFiles(distRoot)).filter(
    (path) => normalizedRelativePath(path, distRoot) !== distManifest,
  );
  identity.distHash = await calculateFilesHash(distFiles, distRoot);
  await writeFile(
    manifestPath,
    `${JSON.stringify(identity, null, 2)}\n`,
    "utf8",
  );
  process.stdout.write(
    `PortViewer frontend dist identity: ${identity.distHash}\n`,
  );
}

if (process.argv.includes("--finalize")) {
  await finalizeDistIdentity();
} else {
  await generateSourceIdentity();
}
